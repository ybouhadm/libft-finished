#include "libft.h"

void	ft_putnbr_fd(int n, int fd)
{
	long	value;

	value = n;
	if (value < 0)
	{
		ft_putchar_fd('-', fd);
		value = -value;
	}
	if (value >= 10)
		ft_putnbr_fd((int)(value / 10), fd);
	ft_putchar_fd((char)('0' + value % 10), fd);
}
