#include "libft.h"
#include <stdlib.h>

char	*ft_substr(char const *s, unsigned int start, size_t len)
{
	char	*result;
	size_t	slen;

	slen = ft_strlen(s);
	if (start >= slen)
		len = 0;
	else if (len > slen - start)
		len = slen - start;
	result = (char *)malloc(len + 1);
	if (!result)
		return (NULL);
	if (len)
		ft_memcpy(result, s + start, len);
	result[len] = '\0';
	return (result);
}
